// Builds src/data/personaTabs.tsx from the home snapshot: the persona
// section's header markup and the six tab triggers (icon + label), each
// converted to JSX. Panel bodies come from the client-captured panels.
import { readFileSync, writeFileSync } from 'node:fs'
import { parseDOM } from 'htmlparser2'
import { convertFragment } from './snapshot-to-jsx.mjs'

const html = readFileSync('/tmp/a2m-snapshots/en.html', 'utf8')
const dom = parseDOM(html, { lowerCaseTags: true, lowerCaseAttributeNames: true })

const findBy = (el, pred) => {
  for (const c of el.children ?? []) {
    if (c.type !== 'tag') continue
    if (pred(c)) return c
    const deep = findBy(c, pred)
    if (deep) return deep
  }
  return null
}
const childElements = (el) => (el.children ?? []).filter((c) => c.type === 'tag')
const textOf = (el) => {
  let out = ''
  for (const c of el.children ?? []) {
    if (c.type === 'text') out += c.data
    else if (c.type === 'tag') out += textOf(c)
  }
  return out.replace(/\s+/g, ' ').trim()
}
const serialize = (el) => {
  // minimal re-serialization for parseDOM round-trip
  let out = `<${el.name}`
  for (const [k, v] of Object.entries(el.attribs ?? {})) out += ` ${k}="${v}"`
  out += '>'
  for (const c of el.children ?? []) {
    if (c.type === 'text') out += c.data
    else if (c.type === 'tag') out += serialize(c)
  }
  out += `</${el.name}>`
  return out
}

const main = dom.find((n) => n.name === 'main')
const tablist = findBy(main, (n) => n.attribs?.role === 'tablist')
const triggers = childElements(tablist).filter((n) => n.attribs?.role === 'tab')
if (triggers.length !== 6) throw new Error(`expected 6 persona triggers, got ${triggers.length}`)

// The section containing the tablist ("Who's in the room").
const section = findBy(main, (n) => {
  if (n.name !== 'section') return false
  return !!findBy(n, (m) => m.attribs?.role === 'tablist')
})
// Section header: children before the div.mt-10 wrapper.
const sectionChildren = childElements(section)
const headerDiv = sectionChildren[0] // mx-auto container
const headerInner = childElements(headerDiv) // [header block, div.mt-10]
const headerBlock = headerInner[0]

const header = convertFragment(serialize(headerBlock))

// id from aria-controls suffix: radix-...-content-majors -> majors
const items = triggers.map((trigger) => {
  const id = (trigger.attribs['aria-controls'] ?? '').split('-content-').pop()
  const svg = childElements(trigger).find((c) => c.name === 'svg')
  const label = textOf(trigger).replace(/\s+/g, ' ').replace(/^[^A-Za-z]*/, '')
  const icon = convertFragment(serialize(svg))
  return { id, label: label.replace(/\s*\b(majors|juniors|investors|services|governments|buyers)\b/i, (m) => m).trim(), icon: icon.jsx }
})

const out = `// Generated by tools/build-persona-data.mjs from the archived home snapshot.
// "Who's in the room" persona tabs: section header + trigger icons/labels.
import type { ReactNode } from 'react'
import { Link } from 'react-router-dom'

export const personaSectionClassName = ${JSON.stringify(section.attribs.class.replace(/\bclone-reveal\b\s*/g, '').replace(/\ba2m-reveal\b\s*/g, 'a2m-reveal ').trim())}
` + '\n'

// header as a component snippet
const headerJsx = header.jsx.split('\n').map((l) => '  ' + l).join('\n')
let result = out
result += `export function PersonaSectionHeader() {\n  return (\n${headerJsx}\n  )\n}\n\n`
result += 'export type PersonaTab = { id: string; label: string; icon: ReactNode }\n\n'
result += 'export const personaTabs: PersonaTab[] = [\n'
for (const item of items) {
  const icon = item.icon.split('\n').map((l) => '      ' + l).join('\n')
  result += `  {\n    id: ${JSON.stringify(item.id)},\n    label: ${JSON.stringify(item.label)},\n    icon: (\n${icon}\n    ),\n  },\n`
}
result += ']\n'
writeFileSync('/Users/asaklex/dev/KOSSOKO/a2m-2027/src/data/personaTabs.tsx', result)
console.log('personaTabs.tsx written;', items.map((i) => i.label).join(' | '))
